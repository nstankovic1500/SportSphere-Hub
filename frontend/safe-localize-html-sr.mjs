const attributeReplacements = [
  [/title="Approve request"/g, 'title="Odobri zahtev"'],
  [/title="Reject request"/g, 'title="Odbij zahtev"'],
  [/placeholder="Search"/g, 'placeholder="Pretraga"'],
  [/placeholder="Name or description"/g, 'placeholder="Naziv ili opis"'],
  [/alt="Profile image"/g, 'alt="Profilna slika"'],
  [/alt="Facility preview"/g, 'alt="Pregled objekta"'],
  [/alt="Product preview"/g, 'alt="Pregled proizvoda"'],
];

const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    const stats = statSync(fullPath);
    if (stats.isDirectory()) {
      walk(fullPath);
      continue;
    }
    if (!fullPath.endsWith('.html')) {
      continue;
    }
    let content = readFileSync(fullPath, 'utf8');
    for (const [from, to] of rawReplacements) {
      content = content.split(from).join(to);
    }
    for (const [pattern, replacement] of attributeReplacements) {
      content = content.replace(pattern, replacement);
    }
    writeFileSync(fullPath, content, 'utf8');
  }
};

walk(rootDir);
